
local sb = Ponder.API.NewStoryboard("improved_clipping", "tutorials", "dual-hitplane")
sb:WithMenuName("Dual hitplane")
sb:WithPlaybackName("Dual hitplane")
sb:WithModelIcon("models/props_junk/wood_crate001a.mdl")
sb:WithDescription("Cut along the line where two surfaces meet.")
sb:SetPrimaryLanguage("en")
sb:WithIndexOrder(3) -- Ponder lists the highest first

local Model, BoxPos, Half, ToolPos = "models/hunter/blocks/cube1x1x1.mdl", Vector(0, 0, 40), 23.725, Vector(90, -90, 90)

local c = sb:Chapter("Dual hitplane")
c:AddInstruction("MoveCameraLookAt", {Target = BoxPos, Distance = 1400, Angle = 55, Height = 500, Length = 0.6})
c:AddInstruction("PlaceModel", {Name = "prop", Model = Model, Position = BoxPos, Length = 0})
c:AddInstruction("ColorModel", {Target = "prop", Color = Color(230, 170, 60), Length = 0})
c:AddInstruction("ShowToolgun", {Tool = "improved_clipping", Position = ToolPos, Length = 0.375})
c:AddInstruction("Caption", {Text = "Dual Hitplane Intersection: left click two different surfaces to cut along where they meet.", FadeInOutTime = 0.225, TextLength = 2.325})
c:AddDelay(0.75)
c:AddInstruction("PlaceToolMenu", {Name = "menu", Tool = "improved_clipping"})
c:AddDelay(0.9)
c:AddDelay(c:AddInstruction("SetToolOption", {Name = "menu", ConVar = "improved_clipping_mode", Value = 0}).Length)
c:AddDelay(1.5)
c:AddInstruction("RemovePanel", {Name = "menu", Length = 0.3})
c:AddDelay(0.3)
c:AddInstruction("MoveToolgunTo", {Position = ToolPos, Length = 0.45})
c:AddDelay(0.525)
c:AddDelay(c:AddInstruction("KeyPress", {Name = "key", Key = "Left Click"}).PressedAt)
c:AddInstruction("ClickToolgun", {Position = BoxPos + Vector(0, 0, Half), Length = 0.375})
c:AddDelay(0.375)
c:AddInstruction("DebugCross", {Name = "hit1", Position = BoxPos + Vector(0, 0, Half), Size = 20, IgnoreZ = true, Color = Color(0, 255, 0)})
c:AddInstruction("MoveToolgunTo", {Position = ToolPos, Length = 0.45})
c:AddDelay(0.525)
c:AddDelay(c:AddInstruction("KeyPress", {Name = "key", Key = "Left Click"}).PressedAt)
c:AddInstruction("ClickToolgun", {Position = BoxPos + Vector(Half, 0, 0), Length = 0.375})
c:AddDelay(0.375)
c:AddInstruction("DebugCross", {Name = "hit2", Position = BoxPos + Vector(Half, 0, 0), Size = 20, IgnoreZ = true, Color = Color(0, 255, 0)})
c:AddInstruction("Caption", {Text = "The plane passes through the line where the two surfaces meet, halfway between them.", FadeInOutTime = 0.225, TextLength = 2.4})
local normal = Vector(1, 0, 1):GetNormalized()
local edgeDist = normal:Dot(Vector(Half, 0, Half)) - 14
c:AddInstruction("ClipOverlay", {Normal = normal, Distance = edgeDist})
c:AddDelay(2.625)
c:AddInstruction("Caption", {Text = "Right click to apply.", FadeInOutTime = 0.225, TextLength = 3.15})
c:AddDelay(0.6)
c:AddInstruction("MoveToolgunTo", {Position = ToolPos, Length = 0.45})
c:AddDelay(0.525)
c:AddDelay(c:AddInstruction("KeyPress", {Name = "key", Key = "Right Click"}).PressedAt)
c:AddInstruction("ClickToolgun", {Position = BoxPos, Length = 0.375})
c:AddDelay(0.375)
c:AddInstruction("EndClipOverlay", {})
c:AddInstruction("ClipModel", {Target = "prop", Clips = {{Normal = normal, Distance = edgeDist}}})
c:AddInstruction("RemoveDebugOverlay", {Name = "hit1"})
c:AddInstruction("RemoveDebugOverlay", {Name = "hit2"})
c:AddDelay(1.875)
c:AddInstruction("HideToolgun", {Length = 0.375})
c:AddDelay(0.375)
